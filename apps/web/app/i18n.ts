export const MESSAGES: Record<Locale, Record<TranslationKey, string>> = {
  "zh-CN": zhCN,
  en,
};

export function isLocale(value: string | null | undefined): value is Locale {
  return typeof value === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function translate(locale: Locale, key: TranslationKey, values?: TranslationValues): string {
  const template = MESSAGES[locale][key];
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    values[name] === undefined ? placeholder : String(values[name])
  ));
}

/** Small inline helper for runtime-owned labels that are not part of the shared shell dictionary. */
export function localizedText(locale: Locale, zhCNText: string, englishText: string): string {
  return locale === "en" ? englishText : zhCNText;
}
